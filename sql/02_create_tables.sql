        user_id FLOAT NULL,
        likes FLOAT NULL,
        dislikes FLOAT NULL,
        verification_status NVARCHAR(255) NULL,
        recommend NVARCHAR(255) NULL,
        title NVARCHAR(255) NULL,
        comment NVARCHAR(MAX) NULL,
        advantages NVARCHAR(255) NULL,
        disadvantages NVARCHAR(255) NULL
    );
END;
GO
IF OBJECT_ID(N'stg.comment', N'U') IS NULL
BEGIN
    CREATE TABLE stg.comment (
        product_id FLOAT NULL,
        confirmed_at NVARCHAR(255) NULL,
        comment NVARCHAR(MAX) NULL
    );
END;
GO

-- Dimension tables. Surrogate keys are identities except the YYYYMMDD DateKey.
IF OBJECT_ID(N'dw.DimCustomer', N'U') IS NULL
BEGIN
    CREATE TABLE dw.DimCustomer (
        CustomerKey INT IDENTITY(1,1) NOT NULL,
        CustomerID BIGINT NOT NULL,
        CONSTRAINT PK_DimCustomer PRIMARY KEY CLUSTERED (CustomerKey),
        CONSTRAINT UQ_DimCustomer_CustomerID UNIQUE (CustomerID)
    );
END;
GO
IF OBJECT_ID(N'dw.DimProduct', N'U') IS NULL
BEGIN
    CREATE TABLE dw.DimProduct (
        ProductKey INT IDENTITY(1,1) NOT NULL,
        ProductID BIGINT NOT NULL,
        ProductTitle NVARCHAR(500) NULL,
        CategoryTitleFa NVARCHAR(300) NULL,
        BrandNameFa NVARCHAR(200) NULL,
        ProductGroupCode NVARCHAR(30) NULL,
        TitleSource VARCHAR(20) NOT NULL,
        CategorySource VARCHAR(20) NOT NULL,
        CONSTRAINT PK_DimProduct PRIMARY KEY CLUSTERED (ProductKey),
        CONSTRAINT UQ_DimProduct_ProductID UNIQUE (ProductID)
    );
END;
GO
IF OBJECT_ID(N'dw.DimCity', N'U') IS NULL
BEGIN
    CREATE TABLE dw.DimCity (
        CityKey INT IDENTITY(1,1) NOT NULL,
        CityNameFa NVARCHAR(150) NOT NULL,
        CONSTRAINT PK_DimCity PRIMARY KEY CLUSTERED (CityKey),
        CONSTRAINT UQ_DimCity_CityNameFa UNIQUE (CityNameFa)
    );
END;
GO
IF OBJECT_ID(N'dw.DimDate', N'U') IS NULL
BEGIN
    CREATE TABLE dw.DimDate (
        DateKey INT NOT NULL,
        FullDate DATE NOT NULL,
        YearNumber SMALLINT NULL,
        QuarterNumber TINYINT NULL,
        MonthNumber TINYINT NULL,
        MonthName NVARCHAR(20) NULL,
        DayNumber TINYINT NULL,
        DayOfWeekNumber TINYINT NULL,
        IsWeekend BIT NULL,
        PersianDate NVARCHAR(10) NULL,
        PersianYear SMALLINT NULL,
        PersianMonthNumber TINYINT NULL,
        PersianMonthName NVARCHAR(20) NULL,
        PersianQuarter TINYINT NULL,
        CONSTRAINT PK_DimDate PRIMARY KEY CLUSTERED (DateKey),
        CONSTRAINT UQ_DimDate_FullDate UNIQUE (FullDate)
    );
END;
GO

-- FactOrderLine grain: ONE SOURCE ORDER LINE; OrderID is not unique.
IF OBJECT_ID(N'dw.FactOrderLine', N'U') IS NULL
BEGIN
    CREATE TABLE dw.FactOrderLine (
        OrderLineKey INT IDENTITY(1,1) NOT NULL,
        OrderID BIGINT NOT NULL,
        CustomerKey INT NOT NULL,
        ProductKey INT NOT NULL,
        CityKey INT NOT NULL,
        DateKey INT NOT NULL,
        OrderFinalizedAt DATETIME2(7) NULL,
        Quantity INT NOT NULL,
        RecordedAmount DECIMAL(19,2) NULL,
        CONSTRAINT PK_FactOrderLine PRIMARY KEY CLUSTERED (OrderLineKey)
    );
END;
GO

-- Foreign-key relationships in the source schema (four FKs).
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_Fact_Customer' AND parent_object_id = OBJECT_ID(N'dw.FactOrderLine'))
    ALTER TABLE dw.FactOrderLine WITH CHECK ADD CONSTRAINT FK_Fact_Customer FOREIGN KEY (CustomerKey) REFERENCES dw.DimCustomer(CustomerKey);
GO
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_Fact_Product' AND parent_object_id = OBJECT_ID(N'dw.FactOrderLine'))
    ALTER TABLE dw.FactOrderLine WITH CHECK ADD CONSTRAINT FK_Fact_Product FOREIGN KEY (ProductKey) REFERENCES dw.DimProduct(ProductKey);
GO
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_Fact_City' AND parent_object_id = OBJECT_ID(N'dw.FactOrderLine'))
    ALTER TABLE dw.FactOrderLine WITH CHECK ADD CONSTRAINT FK_Fact_City FOREIGN KEY (CityKey) REFERENCES dw.DimCity(CityKey);
GO
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_Fact_Date' AND parent_object_id = OBJECT_ID(N'dw.FactOrderLine'))
    ALTER TABLE dw.FactOrderLine WITH CHECK ADD CONSTRAINT FK_Fact_Date FOREIGN KEY (DateKey) REFERENCES dw.DimDate(DateKey);
GO
