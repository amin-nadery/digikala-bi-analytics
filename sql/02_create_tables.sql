/*
DigiKala BI Analytics — 02_create_tables.sql
Nine tables: four staging tables and a four-dimension/one-fact star schema.
Column names/types/nullability/keys based on the user's SSMS-generated script.sql.
Simplified for portability: server file paths, compatibility level, default
DB options, and autogenerated storage options have been intentionally omitted.
SAFE: Creates missing tables/FKs only. No INSERT, UPDATE or DELETE.
Prerequisite: 01_create_database.sql.
*/
USE [DigikalaBI];
GO
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO

-- Staging layer: source-file structure retained.
IF OBJECT_ID(N'stg.orders', N'U') IS NULL
BEGIN
    CREATE TABLE stg.orders (
        ID_Order INT NOT NULL,
        ID_Customer INT NOT NULL,
        ID_Item INT NOT NULL,
        DateTime_CartFinalize DATETIME2(7) NOT NULL,
        Amount_Gross_Order FLOAT NOT NULL,
        city_name_fa NVARCHAR(50) NOT NULL,
        Quantity_item FLOAT NOT NULL
    );
END;
GO
IF OBJECT_ID(N'stg.product', N'U') IS NULL
BEGIN
    CREATE TABLE stg.product (
        id FLOAT NULL,
        product_title_fa NVARCHAR(255) NULL,
        product_title_en NVARCHAR(255) NULL,
        url_code NVARCHAR(255) NULL,
        title_alt NVARCHAR(255) NULL,
        category_title_fa NVARCHAR(255) NULL,
        category_keywords NVARCHAR(255) NULL,
        brand_name_fa NVARCHAR(255) NULL,
        brand_name_en NVARCHAR(255) NULL,
        product_attributes NVARCHAR(MAX) NULL
    );
END;
GO
IF OBJECT_ID(N'stg.keifiat', N'U') IS NULL
BEGIN
    CREATE TABLE stg.keifiat (
        product_id FLOAT NULL,
        product_title NVARCHAR(255) NULL,
